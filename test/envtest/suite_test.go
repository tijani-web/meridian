/*
Package envtest provides integration tests for the Meridian v1alpha1 API CRDs and admission
webhooks, running against a real kube-apiserver binary managed by controller-runtime's envtest.

No mocks are used here — every test exercises the actual OpenAPI schema validation and the
defaulting/validating webhook handlers via the apiserver admission chain.
*/
package envtest

import (
	"context"
	"crypto/tls"
	"fmt"
	"net"
	"path/filepath"
	"testing"
	"time"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"

	"k8s.io/client-go/rest"
	ctrl "sigs.k8s.io/controller-runtime"
	"sigs.k8s.io/controller-runtime/pkg/client"
	"sigs.k8s.io/controller-runtime/pkg/envtest"
	logf "sigs.k8s.io/controller-runtime/pkg/log"
	"sigs.k8s.io/controller-runtime/pkg/log/zap"

	clientgoscheme "k8s.io/client-go/kubernetes/scheme"
	metricsserver "sigs.k8s.io/controller-runtime/pkg/metrics/server"

	meridianv1alpha1 "github.com/tijani-web/meridian/api/v1alpha1"
	"k8s.io/apimachinery/pkg/runtime"
)

var (
	cfg       *rest.Config
	k8sClient client.Client
	testEnv   *envtest.Environment
	scheme    *runtime.Scheme
	// mgrCancel shuts down the manager started in BeforeSuite.
	mgrCancel context.CancelFunc
)

// TestAPIs is the Ginkgo entry point registered with go test.
// All Ginkgo specs in this package run under this suite.
func TestAPIs(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Meridian API Webhook Suite")
}

var _ = BeforeSuite(func() {
	// Structured logging so test output is readable under go test -v.
	logf.SetLogger(zap.New(zap.WriteTo(GinkgoWriter), zap.UseDevMode(true)))

	// Locate the CRD manifests generated by controller-gen.
	// The path is relative to this test package so it works regardless of working directory.
	crdPaths := []string{
		filepath.Join("..", "..", "config", "crd", "bases"),
	}

	// Locate the webhook manifests; envtest wires them into the built-in apiserver admission chain.
	webhookPaths := []string{
		filepath.Join("..", "..", "config", "webhook"),
	}

	testEnv = &envtest.Environment{
		CRDDirectoryPaths:     crdPaths,
		WebhookInstallOptions: envtest.WebhookInstallOptions{Paths: webhookPaths},
		// ErrorIfCRDPathMissing causes the suite to fail fast if CRD YAMLs are absent,
		// rather than silently running tests without schema enforcement.
		ErrorIfCRDPathMissing: true,
	}

	var err error
	cfg, err = testEnv.Start()
	Expect(err).NotTo(HaveOccurred())
	Expect(cfg).NotTo(BeNil())

	scheme = runtime.NewScheme()
	Expect(clientgoscheme.AddToScheme(scheme)).To(Succeed())
	Expect(meridianv1alpha1.AddToScheme(scheme)).To(Succeed())

	k8sClient, err = client.New(cfg, client.Options{Scheme: scheme})
	Expect(err).NotTo(HaveOccurred())
	Expect(k8sClient).NotTo(BeNil())

	// Wire the webhook server so admission hooks are active during tests.
	// We pass in the envtest WebhookInstallOptions so the manager binds to the
	// same host:port that the apiserver is configured to forward admission requests to.
	wh := testEnv.WebhookInstallOptions
	mgr, err := ctrl.NewManager(cfg, ctrl.Options{
		Scheme:         scheme,
		LeaderElection: false,
		WebhookServer:  newWebhookServer(wh),
		// Disable metrics and health endpoints to avoid port conflicts in test.
		Metrics:                metricsserver.Options{BindAddress: "0"},
		HealthProbeBindAddress: "0",
	})
	Expect(err).NotTo(HaveOccurred())

	// Register all three webhook pairs with the manager.
	Expect((&meridianv1alpha1.GPUQueue{}).SetupWebhookWithManager(mgr)).To(Succeed())
	Expect((&meridianv1alpha1.GPUWorkload{}).SetupWebhookWithManager(mgr)).To(Succeed())
	Expect((&meridianv1alpha1.InferenceDeployment{}).SetupWebhookWithManager(mgr)).To(Succeed())

	// Run the manager in the background for the duration of the suite.
	// mgrCancel stops it in AfterSuite without interfering with os signals.
	var mgrCtx context.Context
	mgrCtx, mgrCancel = context.WithCancel(context.Background())
	go func() {
		defer GinkgoRecover()
		Expect(mgr.Start(mgrCtx)).To(Succeed())
	}()

	// Wait for the webhook server to be responsive before running specs.
	// We dial the TLS serving port configured by envtest to ensure the listener is active.
	dialer := &net.Dialer{Timeout: time.Second}
	addrPort := net.JoinHostPort(testEnv.WebhookInstallOptions.LocalServingHost, fmt.Sprintf("%d", testEnv.WebhookInstallOptions.LocalServingPort))
	Eventually(func() error {
		conn, err := tls.DialWithDialer(dialer, "tcp", addrPort, &tls.Config{InsecureSkipVerify: true})
		if err != nil {
			return err
		}
		return conn.Close()
	}, 10*time.Second, 100*time.Millisecond).Should(Succeed())
})

var _ = AfterSuite(func() {
	By("stopping the manager")
	mgrCancel()

	By("tearing down the test environment")
	Expect(testEnv.Stop()).To(Succeed())
})
